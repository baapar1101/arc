def _ctx(*, business_id: int = 7, user_id: int = 9, db=None):
    user = MagicMock()
    user.get_user_id.return_value = user_id
    user.can_access_business.return_value = True
    return {"db": db if db is not None else MagicMock(), "business_id": business_id, "user_context": user}


def test_remaining_tools_registered_and_manifested():
    parsed = parse_registered_tool_fields()
    for name in NEW_TOOLS:
        assert name in parsed, name
        entry = get_manifest_entry(name)
        assert entry is not None, name
        assert entry.domains
        fields = parsed[name]
        if fields["is_readonly"]:
            assert fields["requires_approval"] is False, name
            assert is_write_function(name) is False or get_manifest_entry(name).intent_write is False
        else:
            assert fields["requires_approval"] is True, name
            assert fields["is_readonly"] is False, name
            assert get_manifest_entry(name).intent_write is True, name
    for name in WRITE_MUST_CONFIRM:
        assert parsed[name]["requires_approval"] is True
        assert get_manifest_entry(name).always_confirm is True or get_manifest_entry(name).intent_write is True


